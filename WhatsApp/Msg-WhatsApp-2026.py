import pywhatkit
import time

# Вказуємо номер телефону одержувача обов'язково з кодом країни (наприклад, +380 для України)
phone_number = "+380505953204"

# Текст повідомлення, яке ми хочемо надіслати
message = "Привіт! Це повідомлення надіслано автоматично за допомогою Python. 😎"

# Час відправки у 24-годинному форматі
# Наприклад, якщо зараз 14:25, ставимо час на кілька хвилин вперед, щоб браузер встиг відкритися
send_hour = 21
send_minute = 6

print("Запуск програми... Зачекайте.")

try:
    # Функція sendwhatmsg відкриває WhatsApp Web і планує відправку
    # wait_time=15: скрипт чекатиме 15 секунд після відкриття браузера для завантаження сторінки
    # tab_close=True: вкладка закриється після відправки
    # close_time=3: час у секундах перед закриттям вкладки після повідомлення
    pywhatkit.sendwhatmsg(
        phone_no=phone_number,
        message=message,
        time_hour=send_hour,
        time_min=send_minute,
        wait_time=15,
        tab_close=True,
        close_time=3
    )
    print("Повідомлення успішно заплановано та буде відправлено у вказаний час!")

except Exception as e:
    # Обробка можливих помилок (наприклад, відсутність інтернету)
    print(f"Виникла помилка під час відправки: {e}")