# CELLULE 6 : Comprendre l'architecture U-Net (Segmentation)
# ==========================================
# Note: Entraîner un U-Net prend du temps. Regardons son architecture interne,
# notamment les fameuses "skip connections".

class MinimalUNet(nn.Module):
    def __init__(self):
        super(MinimalUNet, self).__init__()
        # Encodeur
        self.enc_conv1 = nn.Conv2d(1, 64, kernel_size=3, padding=1)
        self.pool1 = nn.MaxPool2d(2)

        self.enc_conv2 = nn.Conv2d(64, 128, kernel_size=3, padding=1)
        self.pool2 = nn.MaxPool2d(2)

        # Décodeur
        # ConvTranspose permet de suréchantillonner (agrandir l'image : upsampling)
        self.upconv1 = nn.ConvTranspose2d(128, 64, kernel_size=2, stride=2)
        # Remarquez les canaux en entrée (64 de l'encodage + 64 de la skip connection)
        self.dec_conv1 = nn.Conv2d(128, 64, kernel_size=3, padding=1)

        self.upconv2 = nn.ConvTranspose2d(64, 64, kernel_size=2, stride=2)
        self.final_conv = nn.Conv2d(128, 2, kernel_size=1) # 2 classes : Fond / Objet

    def forward(self, x):
        # Encodage
        e1 = F.relu(self.enc_conv1(x))
        p1 = self.pool1(e1)

        e2 = F.relu(self.enc_conv2(p1))
        p2 = self.pool2(e2)

        # Décodage avec Skip Connections (torch.cat concatène les features)
        d1 = self.upconv1(p2)
        d1_cat = torch.cat([d1, e2], dim=1) # <- LA SKIP CONNECTION
        d1_out = F.relu(self.dec_conv1(d1_cat))

        d2 = self.upconv2(d1_out)
        d2_cat = torch.cat([d2, e1], dim=1) # <- LA SKIP CONNECTION
        out = self.final_conv(d2_cat)

        return out

dummy_input = torch.randn(1, 1, 28, 28)
unet_model = MinimalUNet()
output = unet_model(dummy_input)

print(f"Format d'entrée de U-Net : {dummy_input.shape}")
print(f"Format de sortie de U-Net : {output.shape}")
